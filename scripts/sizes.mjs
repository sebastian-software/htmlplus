// Measures each entry the way a bundler consumes it, then writes docs/SIZES.md or checks it and the limits.
import { build } from "esbuild";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const output = new URL("../docs/SIZES.md", import.meta.url);

// Gzipped bytes. Raise a limit deliberately, not by habit.
const limits = {
  all: 135_000,
  "date-range-picker": 55_000,
  "date-picker": 55_000,
  select: 40_000,
  combobox: 40_000,
  iban: 8_000,
  switch: 3_500,
};

async function measure(entry) {
  const { outputFiles, metafile } = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    bundle: true,
    minify: true,
    write: false,
    metafile: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    define: { "process.env.NODE_ENV": '"production"' },
    logLevel: "silent",
  });
  const content = outputFiles[0].contents;
  const groups = { own: 0, zag: 0, other: 0 };
  for (const { inputs } of Object.values(metafile.outputs)) {
    for (const [input, { bytesInOutput }] of Object.entries(inputs)) {
      const group = !input.includes("node_modules/") ? "own" : input.includes("@zag-js/") ? "zag" : "other";
      groups[group] += bytesInOutput;
    }
  }
  const total = groups.own + groups.zag + groups.other;
  return {
    minified: content.length,
    gzipped: gzipSync(content).length,
    own: Math.round((groups.own / total) * 100),
  };
}

const kilobytes = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;
const names = (await readdir(new URL("../src/elements/", import.meta.url))).map((name) => name.replace(/\.ts$/, ""));
const rows = await Promise.all(names.map(async (name) => ({ name, ...(await measure(`src/elements/${name}.ts`)) })));
rows.sort((a, b) => a.gzipped - b.gzipped);
const all = { name: "all", ...(await measure("src/index.ts")) };
const row = ({ name, minified, gzipped, own }) =>
  `| ${name === "all" ? "All elements" : `\`h6-${name}\``} | ${kilobytes(minified)} | ${kilobytes(gzipped)} | ${own}% |`;

const table = [
  "# Element sizes",
  "",
  "Generated by `npm run docs:sizes`. Each row is one entry, such as `htmlplus/switch`, bundled and minified on its own with everything it needs. Elements share code, so a page using several costs less than the sum of its rows: compare the last row.",
  "",
  "The last column is the share of the minified bytes that is html+'s own code, and the rest is Zag and other dependencies. Sizes exclude your application and any styles you add. Run `node scripts/sizes.mjs --check` to compare the limits.",
  "",
  "| Element | Minified | Gzipped | Own code |",
  "| --- | ---: | ---: | ---: |",
  ...[...rows, all].map(row),
  "",
].join("\n");

const measured = Object.fromEntries([...rows, all].map((item) => [item.name, item]));
let failed = false;
for (const [name, limit] of Object.entries(limits)) {
  if (measured[name].gzipped > limit) {
    failed = true;
    console.error(`${name}: ${measured[name].gzipped} bytes gzipped is over its limit of ${limit}.`);
  }
}
if (check) {
  // Compression output varies by platform, so only minified bytes decide whether the table is stale.
  const current = await readFile(output, "utf8").catch(() => "");
  for (const item of [...rows, all]) {
    const label = item.name === "all" ? "All elements" : `\`h6-${item.name}\``;
    if (!current.includes(`| ${label} | ${kilobytes(item.minified)} |`)) {
      failed = true;
      console.error(`docs/SIZES.md is out of date for ${label}. Run npm run docs:sizes.`);
      break;
    }
  }
} else {
  await writeFile(output, table);
}
if (failed) process.exit(1);
console.log(check ? "Sizes are within their limits and current." : "Generated docs/SIZES.md.");
